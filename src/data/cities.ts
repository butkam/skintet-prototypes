/** Lowercase, one apostrophe, no «м.» prefix */
const normalize = (s: string) =>
  s
    .toLowerCase()
    .replace(/['`ʼ‘]/g, '’')
    .replace(/^\s*(м\.|місто)\s*/, '')
    .replace(/\s+/g, ' ')
    .trim()

const words = (s: string) => normalize(s).split(/[\s-]+/)

/** Exact city by name or old name — used to accept typed input and validate */
export function findCity(query: string): City | undefined {
  const q = normalize(query)
  if (!q) return undefined
  return cities.find((c) => normalize(c.name) === q || c.aliases?.some((a) => normalize(a) === q))
}

/** Suggestions: prefix matches first, then word/old-name matches, then substring; bigger cities win ties */
export function searchCities(query: string, limit = 6): City[] {
  const q = normalize(query)
  if (!q) return cities.slice(0, limit)

  const score = (c: City) => {
    const name = normalize(c.name)
    if (name.startsWith(q)) return 0
    if (words(c.name).some((w) => w.startsWith(q))) return 1
    if (c.aliases?.some((a) => normalize(a).startsWith(q))) return 2
    if (name.includes(q)) return 3
    return -1
  }

  return cities
    .map((city, i) => ({ city, i, s: score(city) }))
    .filter((m) => m.s >= 0)
    .sort((a, b) => a.s - b.s || a.i - b.i)
    .slice(0, limit)
    .map((m) => m.city)
}
