"""Isometric line-art set of cosmetic jars (Linear FIG 0.2 manner), written as a static SVG.

    python3 tools/placeholder-jars.py public/skin-id/assets/prototype/placeholder-jars.svg

Camera: azimuth 45°, elevation 30°. A floor circle of radius r projects to an ellipse rx=r, ry=r/2.
Two solid inks, two weights: each solid's silhouette is dark and heavier, edges and seams inside it
light and thinner. Solids are filled with the card colour and painted back to front, so they hide what is
behind them; no tints, no shadows.
"""
import math, sys

SIN_E, COS_E = 0.5, math.cos(math.radians(30))
K = math.sqrt(0.5)

def P(x, y, z):
    return ((x - y) * K, (x + y) * K * SIN_E - z * COS_E)

PAPER = '#f5f5f5'   # card background (.img-holder img)
INK = '#6b6b6b'     # silhouettes: the site's secondary grey
INK_DETAIL = '#bdbdbd'  # edges and seams inside a silhouette: lighter, so the outline reads first
OUTLINE, DETAIL = 1.5, 1  # px at the 224 card; the drawing (strokes too) scales with the image

out = []      # svg elements, in paint order
pts = []      # every screen point, for fitting

def f(v):
    return f'{v:.2f}'.rstrip('0').rstrip('.')

def line(d, w=DETAIL):
    out.append(f'<path d="{d}" stroke="{INK_DETAIL}" stroke-width="{w}"/>')

def cyl(x, y, z, r, h, grooves=()):
    """A vertical cylinder standing at floor point (x, y), base at height z."""
    cx, by = P(x, y, z)
    _, ty = P(x, y, z + h)
    ry = r * SIN_E
    pts.extend([(cx - r, ty - ry), (cx + r, by + ry)])
    L, R = f(cx - r), f(cx + r)
    rr = f'{f(r)} {f(ry)} 0 0 0'
    # silhouette: left side, front of the base, right side, back of the top
    sil = f'M{L} {f(ty)}V{f(by)}A{rr} {R} {f(by)}V{f(ty)}A{rr} {L} {f(ty)}Z'
    out.append(f'<path d="{sil}" fill="{PAPER}" stroke="none"/>')  # paper first, hides what is behind
    # inside edges: where the top meets the side, and seams across the front
    line(f'M{L} {f(ty)}A{rr} {R} {f(ty)}')
    for gz in grooves:
        _, gy = P(x, y, z + gz)
        line(f'M{L} {f(gy)}A{rr} {R} {f(gy)}')
    out.append(f'<path d="{sil}" stroke-width="{OUTLINE}"/>')  # outline last, over the light ends
    return cx, ty

def ring(x, y, z, r):
    cx, cy = P(x, y, z)
    out.append(f'<ellipse cx="{f(cx)}" cy="{f(cy)}" rx="{f(r)}" ry="{f(r*SIN_E)}" stroke="{INK_DETAIL}" stroke-width="{DETAIL}"/>')

def dots(x, y, z, n=4, step=3.2):
    """A small square patch of dots on the isometric grid, centred on (x, y) at height z."""
    o = (n - 1) / 2
    out.append(f'<g fill="{INK}" stroke="none">')
    for i in range(n):
        for j in range(n):
            px, py = P(x + (i - o) * step, y + (j - o) * step, z)
            out.append(f'<circle cx="{f(px)}" cy="{f(py)}" r=".6"/>')
    out.append('</g>')

# ---- the set, painted back to front (sorted by x + y) ----
parts = []

def jar(x, y, r, body, lid_h, lift=0, lid_r=None, dot=True):
    def draw():
        cyl(x, y, 0, r, body, grooves=(4,))
        if lift:
            ring(x, y, body, r - 5)                  # the opening under the lifted lid
        lr = lid_r or r + 1
        z0 = body + lift
        cyl(x, y, z0, lr, lid_h, grooves=(lid_h / 2,))
        if dot:
            ring(x, y, z0 + lid_h, lr * .62)
            dots(x, y, z0 + lid_h)
    parts.append((x + y, draw))

def bottle(x, y, r, body, cap_r, cap_h):
    def draw():
        cyl(x, y, 0, r, body, grooves=(6, body - 10))
        ring(x, y, body, cap_r + 3)                  # shoulder
        cyl(x, y, body, cap_r, cap_h, grooves=(cap_h / 2,))
    parts.append((x + y, draw))

bottle(-42, -14, 17, 74, 8, 16)
jar(4, -42, 33, 30, 14)
jar(36, 14, 24, 40, 11)
jar(-26, 34, 23, 20, 10, lift=16)

for _, draw in sorted(parts, key=lambda p: p[0]):
    draw()

# ---- fit into the 224 card at ~60% ----
xs, ys = [p[0] for p in pts], [p[1] for p in pts]
w, h = max(xs) - min(xs), max(ys) - min(ys)
s = 224 * .62 / max(w, h)
tx = 112 - s * (min(xs) + w / 2)
ty = 112 - s * (min(ys) + h / 2)

out = [e.replace(f'stroke-width="{OUTLINE}"', f'stroke-width="{f(OUTLINE / s)}"').replace(f'stroke-width="{DETAIL}"', f'stroke-width="{f(DETAIL / s)}"') for e in out]

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="224" height="224" viewBox="0 0 224 224" fill="none">
  <!-- Product placeholder: an isometric set of jars in thin line (generated by tools/placeholder-jars.py) -->
  <rect width="224" height="224" fill="{PAPER}"/>
  <g transform="translate({f(tx)} {f(ty)}) scale({s:.4f})" stroke="{INK}" stroke-linecap="round" stroke-linejoin="round">
    ''' + '\n    '.join(out) + '''
  </g>
</svg>
'''
open(sys.argv[1], 'w').write(svg)
print('scale', round(s, 3), 'elements', len(out))
